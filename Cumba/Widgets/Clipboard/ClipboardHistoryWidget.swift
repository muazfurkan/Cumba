import AppKit
import Observation
import SwiftUI

/// The last texts you copied; click one to copy it again. macOS has no "clipboard changed"
/// event, so while this widget is in the panel it checks the clipboard's change counter
/// once a second (only reading the content when it changed). Items that apps mark as
/// concealed or transient, like passwords, are skipped. Nothing is written to disk.
@MainActor
@Observable
final class ClipboardHistoryWidget: NotchWidget {
  static let kind = "clipboard"
  static var title: String { String(localized: "Clipboard History", comment: "Widget name") }
  static let symbol = "doc.on.clipboard"
  static let size = WidgetSize.regular
  static var summary: String {
    String(
      localized: "Your last copied texts, kept in memory only", comment: "Widget description")
  }

  struct Entry: Identifiable, Equatable {
    let id = UUID()
    let text: String
  }

  static let maxEntries = 20
  /// Longest text kept per entry, in characters.
  static let maxLength = 5_000

  /// Pasteboard types that mean "don't record this" (nspasteboard.org conventions).
  static let skippedTypes: Set<NSPasteboard.PasteboardType> = [
    .init("org.nspasteboard.ConcealedType"), .init("org.nspasteboard.TransientType"),
    .init("org.nspasteboard.AutoGeneratedType"),
  ]

  private(set) var entries: [Entry] = []
  private(set) var lastCopiedID: UUID?

  @ObservationIgnored private var pollTask: Task<Void, Never>?
  @ObservationIgnored private var changeCount = NSPasteboard.general.changeCount

  required init(context: WidgetContext) {
    pollTask = Task { [weak self] in
      while !Task.isCancelled {
        do {
          try await Task.sleep(for: .seconds(1))
        } catch {
          return
        }
        self?.checkPasteboard()
      }
    }
  }

  func makeView() -> AnyView {
    AnyView(ClipboardView(widget: self))
  }

  func makeSettingsView() -> AnyView? {
    AnyView(ClipboardSettingsView(widget: self))
  }

  func shutdown() {
    pollTask?.cancel()
    pollTask = nil
    entries.removeAll()
  }

  func copy(_ entry: Entry) {
    let pasteboard = NSPasteboard.general
    pasteboard.clearContents()
    pasteboard.setString(entry.text, forType: .string)
    changeCount = pasteboard.changeCount
    entries.removeAll { $0.id == entry.id }
    entries.insert(entry, at: 0)
    lastCopiedID = entry.id
  }

  func clear() {
    entries.removeAll()
  }

  private func checkPasteboard() {
    let pasteboard = NSPasteboard.general
    guard pasteboard.changeCount != changeCount else { return }
    changeCount = pasteboard.changeCount
    let types = Set(pasteboard.types ?? [])
    guard types.isDisjoint(with: Self.skippedTypes), let text = pasteboard.string(forType: .string)
    else { return }
    record(text)
  }

  /// Adds a text at the top, without duplicates and within the limits.
  func record(_ text: String) {
    let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
    guard !trimmed.isEmpty else { return }
    let kept = String(trimmed.prefix(Self.maxLength))
    entries.removeAll { $0.text == kept }
    entries.insert(Entry(text: kept), at: 0)
    if entries.count > Self.maxEntries {
      entries.removeLast(entries.count - Self.maxEntries)
    }
    lastCopiedID = nil
  }
}

private struct ClipboardView: View {
  let widget: ClipboardHistoryWidget

  var body: some View {
    WidgetCard {
      VStack(alignment: .leading, spacing: 4) {
        Label("Clipboard", systemImage: "doc.on.clipboard")
          .font(.caption)
          .foregroundStyle(.secondary)
        if widget.entries.isEmpty {
          Text("Copied texts appear here.")
            .font(.caption)
            .foregroundStyle(.secondary)
        } else {
          ScrollView {
            VStack(alignment: .leading, spacing: 2) {
              ForEach(widget.entries) { entry in
                Button {
                  widget.copy(entry)
                } label: {
                  HStack(spacing: 6) {
                    Text(entry.text.replacingOccurrences(of: "\n", with: " "))
                      .lineLimit(1)
                      .truncationMode(.tail)
                    Spacer(minLength: 0)
                    if widget.lastCopiedID == entry.id {
                      Image(systemName: "checkmark")
                        .foregroundStyle(.green)
                        .accessibilityLabel(Text("Copied"))
                    }
                  }
                  .font(.caption)
                  .padding(.vertical, 3)
                  .padding(.horizontal, 4)
                  .contentShape(Rectangle())
                }
                .buttonStyle(.plain)
                .help(Text("Copy again"))
              }
            }
          }
          .scrollIndicators(.never)
        }
      }
    }
  }
}

private struct ClipboardSettingsView: View {
  let widget: ClipboardHistoryWidget

  var body: some View {
    Text(
      "While this widget is in the panel, Cumba checks once a second whether the clipboard changed and keeps your last \(ClipboardHistoryWidget.maxEntries) copied texts in memory. Passwords and other items apps mark as private are skipped, and nothing is saved to disk. macOS may ask once whether Cumba may read what you copy."
    )
    .font(.callout)
    .foregroundStyle(.secondary)
    .fixedSize(horizontal: false, vertical: true)
    Button("Clear History", role: .destructive) { widget.clear() }
      .disabled(widget.entries.isEmpty)
  }
}

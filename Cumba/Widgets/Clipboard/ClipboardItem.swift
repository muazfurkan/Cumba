import AppKit
import ImageIO
import SwiftUI

/// One thing copied: text, a link, an image, files or a new screenshot.
struct ClipboardItem: Identifiable {
  enum Content: Equatable {
    case text(String)
    case link(URL)
    /// Image data from the clipboard, in the type it came in.
    case image(Data, NSPasteboard.PasteboardType)
    case files([URL])
    /// A screenshot file macOS just saved; only its location is kept.
    case screenshot(URL)
  }

  let id = UUID()
  let content: Content
  var date = Date()
  /// The app in front when it was copied.
  var appBundleID: String?
  /// A small picture of an image or screenshot, made off the main thread.
  var thumbnail: CGImage?
  var pixelSize: CGSize?

  var imageBytes: Int {
    if case .image(let data, _) = content { data.count } else { 0 }
  }
}

extension ClipboardItem {
  static let maxLength = 5_000
  /// Larger images on the clipboard are skipped, so the history stays light in memory.
  static let maxImageBytes = 25_000_000

  /// Pasteboard types that mean "don't record this" (nspasteboard.org conventions).
  static let skippedTypes: Set<NSPasteboard.PasteboardType> = [
    .init("org.nspasteboard.ConcealedType"), .init("org.nspasteboard.TransientType"),
    .init("org.nspasteboard.AutoGeneratedType"),
  ]

  static let imageTypes: [NSPasteboard.PasteboardType] = [
    .png, .tiff, .init("public.jpeg"), .init("public.heic"),
  ]

  /// What's on the pasteboard, or nil for nothing worth keeping or anything marked private.
  /// Files come first (Finder also puts their names as text), then text, then images.
  @MainActor
  static func read(from pasteboard: NSPasteboard) -> Content? {
    let types = Set(pasteboard.types ?? [])
    guard types.isDisjoint(with: skippedTypes) else { return nil }
    if let urls = pasteboard.readObjects(
      forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
      !urls.isEmpty
    {
      return .files(urls)
    }
    if let string = pasteboard.string(forType: .string), let content = content(of: string) {
      return content
    }
    for type in imageTypes where types.contains(type) {
      if let data = pasteboard.data(forType: type), !data.isEmpty, data.count <= maxImageBytes {
        return .image(data, type)
      }
    }
    return nil
  }

  /// Text, or a link when it's a single web address. Nil for blank text.
  static func content(of string: String) -> Content? {
    let trimmed = string.trimmingCharacters(in: .whitespacesAndNewlines)
    guard !trimmed.isEmpty else { return nil }
    if !trimmed.contains(where: \.isWhitespace), let url = URL(string: trimmed),
      ["http", "https"].contains(url.scheme?.lowercased()), url.host() != nil
    {
      return .link(url)
    }
    return .text(String(trimmed.prefix(maxLength)))
  }

  /// Puts the item back on the pasteboard. A screenshot goes as its file and its image, so
  /// it pastes into chats and editors alike.
  @MainActor
  func write(to pasteboard: NSPasteboard, screenshotData: Data? = nil) {
    pasteboard.clearContents()
    switch content {
    case .text(let text):
      pasteboard.setString(text, forType: .string)
    case .link(let url):
      pasteboard.writeObjects([url as NSURL])
      pasteboard.setString(url.absoluteString, forType: .string)
    case .image(let data, let type):
      pasteboard.setData(data, forType: type)
    case .files(let urls):
      pasteboard.writeObjects(urls.map { $0 as NSURL })
    case .screenshot(let url):
      pasteboard.writeObjects([url as NSURL])
      if let screenshotData {
        pasteboard.setData(screenshotData, forType: .png)
      }
    }
  }

  /// A thumbnail at most `maxPixels` on its longer side, and the full size. Reads files, so
  /// call it off the main thread.
  nonisolated static func thumbnail(of source: CGImageSource, maxPixels: Int = 360) -> (
    CGImage, CGSize
  )? {
    let options: [CFString: Any] = [
      kCGImageSourceCreateThumbnailFromImageAlways: true,
      kCGImageSourceCreateThumbnailWithTransform: true,
      kCGImageSourceThumbnailMaxPixelSize: maxPixels,
    ]
    guard let image = CGImageSourceCreateThumbnailAtIndex(source, 0, options as CFDictionary)
    else { return nil }
    let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any]
    let width = properties?[kCGImagePropertyPixelWidth] as? Int ?? image.width
    let height = properties?[kCGImagePropertyPixelHeight] as? Int ?? image.height
    return (image, CGSize(width: width, height: height))
  }
}

/// How each kind of item is labeled and colored on its card.
extension ClipboardItem.Content {
  var title: String {
    switch self {
    case .text: String(localized: "Text", comment: "Clipboard item kind")
    case .link: String(localized: "Link", comment: "Clipboard item kind")
    case .image: String(localized: "Image", comment: "Clipboard item kind")
    case .files(let urls):
      urls.count == 1
        ? String(localized: "File", comment: "Clipboard item kind")
        : String(localized: "\(urls.count) Files", comment: "Clipboard item kind")
    case .screenshot: String(localized: "Screenshot", comment: "Clipboard item kind")
    }
  }

  var symbol: String {
    switch self {
    case .text: "text.alignleft"
    case .link: "link"
    case .image: "photo"
    case .files: "doc"
    case .screenshot: "camera.viewfinder"
    }
  }

  var color: Color {
    switch self {
    case .text: .gray
    case .link: .blue
    case .image: .purple
    case .files: .orange
    case .screenshot: .teal
    }
  }
}
